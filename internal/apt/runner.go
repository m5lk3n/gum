// Package apt wraps the small set of apt-get operations gum exposes.
package apt

import (
	"bytes"
	"context"
	"errors"
	"os"
	"os/exec"
	"strings"
	"syscall"
	"time"
)

// AptGet is the absolute path of the apt-get binary. It must match the sudoers rule.
const AptGet = "/usr/bin/apt-get"

// Sudo is the absolute path of the sudo binary.
const Sudo = "/usr/bin/sudo"

// dpkgOptions keep dpkg from prompting about modified configuration files:
// keep the local version, unless there is no local change.
var dpkgOptions = []string{
	"-o", "Dpkg::Options::=--force-confdef",
	"-o", "Dpkg::Options::=--force-confold",
}

// Privileged apt-get argument lists. These are the only commands gum runs as root, and
// SudoersRule emits exactly these, so the code and the sudoers file cannot drift apart.
var (
	argsUpdate     = []string{"-q", "update"}
	argsUpgrade    = append(append([]string{"-q"}, dpkgOptions...), "upgrade", "-y")
	argsAutoremove = append(append([]string{"-q"}, dpkgOptions...), "autoremove", "-y")
)

// Unprivileged simulation: apt-get can simulate as a normal user.
var argsSimulateUpgrade = []string{"-s", "-q", "-o", "Debug::NoLocking=1", "upgrade"}

// Runner executes apt-get with the given arguments and returns its combined output.
type Runner interface {
	Run(ctx context.Context, privileged bool, args ...string) (output string, exitCode int, err error)
}

// ExecRunner runs apt-get on the host, through `sudo -n` for privileged calls unless
// gum already runs as root.
type ExecRunner struct {
	// StopGrace is how long apt-get may take to exit after SIGTERM before it is killed.
	StopGrace time.Duration
}

// Run implements Runner.
func (r ExecRunner) Run(ctx context.Context, privileged bool, args ...string) (string, int, error) {
	name := AptGet
	if privileged && os.Geteuid() != 0 {
		name = Sudo
		args = append([]string{"-n", AptGet}, args...)
	}
	// #nosec G204 -- name and args come from the fixed lists above, never from user input.
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Env = append(os.Environ(), "DEBIAN_FRONTEND=noninteractive", "LC_ALL=C")
	// Interrupting dpkg mid-run is harmful; ask politely first. sudo relays SIGTERM.
	cmd.Cancel = func() error { return cmd.Process.Signal(syscall.SIGTERM) }
	cmd.WaitDelay = r.StopGrace
	if cmd.WaitDelay == 0 {
		cmd.WaitDelay = 30 * time.Second
	}
	var buf bytes.Buffer
	cmd.Stdout = &buf
	cmd.Stderr = &buf
	err := cmd.Run()
	code := 0
	if exitErr, ok := errors.AsType[*exec.ExitError](err); ok {
		code = exitErr.ExitCode()
	}
	return buf.String(), code, err
}

// SudoersRule returns the sudoers(5) snippet that allows user to run exactly the
// privileged commands gum needs, and nothing else.
func SudoersRule(user string) string {
	var b strings.Builder
	b.WriteString("# Generated by `gum --print-sudoers`. Allows only the exact apt-get calls gum makes.\n")
	b.WriteString("Defaults:" + user + " env_keep += \"DEBIAN_FRONTEND\"\n")
	cmds := [][]string{argsUpdate, argsUpgrade, argsAutoremove}
	b.WriteString(user + " ALL=(root) NOPASSWD: ")
	for i, args := range cmds {
		if i > 0 {
			b.WriteString(", \\\n    ")
		}
		b.WriteString(AptGet)
		for _, a := range args {
			b.WriteString(" " + sudoersEscape(a))
		}
	}
	b.WriteString("\n")
	return b.String()
}

// sudoersEscape escapes the characters sudoers treats specially in command arguments.
func sudoersEscape(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `,`, `\,`, `:`, `\:`, `=`, `\=`)
	return r.Replace(s)
}
